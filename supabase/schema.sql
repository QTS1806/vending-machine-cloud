drop policy if exists "demo all machines" on public.machines;
drop policy if exists "demo all products" on public.products;
drop policy if exists "demo all sales" on public.sales;
drop policy if exists "demo all money events" on public.money_events;
drop policy if exists "demo all machine events" on public.machine_events;
drop policy if exists "demo all machine commands" on public.machine_commands;

create policy "demo all machines" on public.machines
for all to anon using (true) with check (true);

create policy "demo all products" on public.products
for all to anon using (true) with check (true);

create policy "demo all sales" on public.sales
for all to anon using (true) with check (true);

create policy "demo all money events" on public.money_events
for all to anon using (true) with check (true);

