create index if not exists products_machine_slot_idx on public.products(machine_id, slot);
create index if not exists sales_machine_created_idx on public.sales(machine_id, created_at desc);
create index if not exists money_events_machine_created_idx on public.money_events(machine_id, created_at desc);
create index if not exists machine_events_machine_created_idx on public.machine_events(machine_id, created_at desc);
create index if not exists machine_commands_machine_status_idx on public.machine_commands(machine_id, status, created_at desc);

